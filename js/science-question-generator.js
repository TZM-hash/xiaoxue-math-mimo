  function pick(deps, items) {
    const list = items.filter(Boolean);
    if (!list.length) return null;
    if (typeof deps.pick === "function") return deps.pick(list) || list[0];
    return list[Math.floor(Math.random() * list.length)] || list[0];
  }

  function uid(deps, prefix) {
    return typeof deps.uid === "function" ? deps.uid(prefix) : `${prefix}-${Date.now()}-${Math.floor(Math.random() * 1000)}`;
  }

  function optionText(options) {
    return options.map((option, index) => `${String.fromCharCode(65 + index)}. ${option}`).join("\n");
  }

  function baseQuestion(deps, point, data) {
    return {
      id: uid(deps, "sq"),
      subject: "science",
      grade: point.grade,
      pointId: point.id,
      topic: point.topic,
      kind: point.label,
      subskills: (point.curriculum?.knowledge?.inquiry || unitFallbacks[point.topic] || []).slice(0, 3),
      commonPitfalls: ["只凭感觉下结论", "没有控制变量", "证据和结论不对应"],
      curriculumBand: point.curriculum?.band || `${point.grade}年级科学 / ${point.label}`,
      sourceType: point.sourceType || "inTextbook",
      sourceLabel: point.sourceLabel || "课内教材",
      ...data
    };
  }

  function choiceQuestion(deps, point, seed) {
    const prompt = `【现象判断】观察或实验后，哪一项最符合“${point.label}”的科学解释？`;
    const options = [seed.correct, ...seed.wrongs].slice(0, 4);
    return baseQuestion(deps, point, {
      questionType: "现象判断",
      answerType: "choice",
      text: `${prompt}\n${optionText(options)}`,
      answer: "A",
      answerLabel: `A. ${seed.correct}`,
      acceptedAnswers: ["A", seed.correct, `A. ${seed.correct}`],
      explanation: seed.evidence,
      steps: [
        "先读清观察到的现象或实验记录。",
        "再找能直接支持结论的证据。",
        "最后排除只凭感觉或无关信息的选项。"
      ]
    });
  }

